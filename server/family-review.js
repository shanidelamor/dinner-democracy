export function applyFamilyReview(recipes, defs) {
  const I = (id, quantity, unit, note = "") => ({
    id,
    quantity,
    unit,
    note,
    name: defs[id][0],
    section: defs[id][1],
  });
  const get = (id) => recipes.find((r) => r.id === id);
  const update = (id, values) => Object.assign(get(id), values);
  const dairyIds = new Set([
    "cream",
    "sourCream",
    "butter",
    "goat",
    "parmesan",
    "mozzarella",
    "cheddar",
    "milkPowder",
    "toffee",
  ]);
  const variation = (r, id, label, changes = {}) => ({
    id,
    label,
    cut: r.cut,
    vegetables: r.vegetables,
    ingredients: r.ingredients,
    steps: r.steps,
    description: r.description,
    notes: r.notes,
    ...changes,
  });

  const thai = get("thai-beef");
  thai.variations = [
    variation(thai, "flank", "Flank steak"),
    variation(thai, "shaved-beef", "Shaved beef", {
      cut: "Shaved beef steak, boneless thinly sliced",
      ingredients: thai.ingredients.map((i) =>
        i.id === "flank" ? I("shavedBeef", i.quantity, i.unit) : i,
      ),
      steps: thai.steps.map((s) =>
        s.replace(
          "Sear steak strips in batches over high heat for 2–3 minutes per side",
          "Sear thin shaved beef in small batches over high heat for 1–2 minutes, just until cooked",
        ),
      ),
    }),
  ];
  update("poke", {
    cut: "Salmon, boneless skinless, sourced for raw consumption",
    ingredients: get("poke").ingredients.map((i) =>
      i.id === "tunaFish" ? I("pokeSalmon", i.quantity, i.unit) : i,
    ),
    steps: [
      "Cook rice and edamame according to package directions. Slice cucumber and avocado.",
      "Use salmon from a supplier who confirms appropriate parasite-destruction freezing and raw-consumption handling. Keep at 40°F or below and thaw in the refrigerator. If the source is uncertain, cook salmon to 145°F and use cooked fish instead.",
      "Dice properly sourced salmon with clean utensils. Toss with tamari and sesame oil just before serving. Assemble with rice, cucumber, avocado, edamame and torn nori.",
    ],
  });
  update("vodka-rigatoni", {
    ingredients: get("vodka-rigatoni").ingredients.map((i) =>
      i.id === "coconutCream" ? I("cream", i.quantity, i.unit) : i,
    ),
    steps: get("vodka-rigatoni").steps.map((s) =>
      s.replace("coconut cream", "regular cream"),
    ),
    notes:
      "Shani confirmed regular cream for this sauce. Use certified gluten-free pasta. Vodka is optional; cooking does not guarantee removal of all alcohol.",
  });
  update("mustard-pork", {
    ingredients: get("mustard-pork").ingredients.map((i) =>
      i.id === "coconutCream" ? I("cream", i.quantity, i.unit) : i,
    ),
    steps: get("mustard-pork").steps.map((s) =>
      s.replace("coconut cream", "regular cream"),
    ),
    notes:
      "Shani chose Dijon and regular cream for this version. Exact historic quantities were unavailable; the measured recipe is proposed for kitchen review.",
  });
  const schnitzel = get("schnitzel"),
    oldSchnitzel = structuredClone(schnitzel);
  schnitzel.vegetables = "Lemon-dressed arugula";
  schnitzel.ingredients = schnitzel.ingredients.filter(
    (i) => !["cabbage", "carrot", "dijon", "riceVinegar"].includes(i.id),
  );
  schnitzel.ingredients.push(I("arugula", 5, "oz"));
  schnitzel.steps = [
    "Toss arugula with a little lemon juice and olive oil just before serving. Reserve lemon wedges for the pork.",
    ...oldSchnitzel.steps
      .slice(1)
      .map((s) => s.replace("and slaw", "and the dressed arugula")),
  ];
  schnitzel.variations = [
    variation(schnitzel, "arugula", "Lemony arugula"),
    variation(oldSchnitzel, "slaw", "Cabbage-carrot slaw"),
  ];
  const burgers = get("lamb-burgers");
  update("lamb-burgers", {
    vegetables: "Tomato, cucumber, red onion & olive salad",
    ingredients: [
      ...burgers.ingredients.filter((i) => i.id !== "potato"),
      I("redOnion", 0.5, "each"),
      I("hummus", 6, "oz"),
    ],
    steps: [
      "Chop tomatoes and cucumber, thinly slice half a red onion, and toss with olives, lemon juice and olive oil.",
      "Combine ground lamb with oregano and minced garlic. Form 3 patties and pan-sear 5–6 minutes per side until centers reach 160°F.",
      "Serve the patties with Greek salad and hummus. No potatoes are included in this version.",
    ],
  });
  get("harissa-lamb").notes +=
    " Shani recalls roasted carrots and goat cheese–tahini sauce; both are included explicitly. Harissa is extremely hot: start with ¼ tsp for the entire batch.";
  update("harissa-chicken", {
    title: "Harissa–Lemon Chicken with Crispy Potatoes & Cauliflower",
    cut: "Chicken thighs, bone-in skin-on",
    vegetables: "Crispy potatoes & roasted cauliflower",
    prep: 15,
    cook: 45,
    ingredients: [
      I("boneThigh", 2.25, "lb"),
      I("potato", 1.25, "lb"),
      I("cauliflower", 1.5, "lb"),
      I("lemon", 1, "each"),
      I("garlic", 3, "each"),
      I("harissa", 0.25, "tsp"),
      I("oil", 2, "tbsp"),
      I("salt", 0.75, "tsp"),
      I("pepper", 0.25, "tsp"),
    ],
    steps: [
      "Heat oven to 425°F. Cut potatoes into 1-inch pieces. Toss potatoes with half the oil and salt and spread on a large sheet pan.",
      "Mix remaining oil with minced garlic, lemon zest and just ¼ tsp of the household’s very hot harissa. Rub onto chicken thighs; arrange skin-side up beside the potatoes.",
      "Roast for 40–45 minutes, adding cauliflower on a second tray for the last 25 minutes. Turn the vegetables once; cook chicken to at least 165°F away from bone.",
      "Rest chicken 5 minutes. Serve the crisp-skinned thighs with golden potatoes, cauliflower, lemon wedges and the lemony pan juices.",
    ],
    notes:
      "A proposed sheet-pan dinner to distinguish it from the shaved-lamb-and-white-bean meal. This version uses bone-in, skin-on thighs, potatoes and cauliflower; it has no white beans or goat cheese–tahini sauce. Use harissa sparingly.",
  });
  const enchiladas = get("enchiladas");
  enchiladas.ingredients = enchiladas.ingredients.filter(
    (i) => !["cabbage", "coconutCream"].includes(i.id),
  );
  enchiladas.ingredients.push(
    I("sourCream", 0.5, "cup"),
    I("lettuce", 1, "each"),
    I("redOnion", 0.5, "each"),
    I("cilantro", 0.25, "cup"),
  );
  enchiladas.vegetables =
    "Fresh romaine, red onion & cilantro; spinach filling";
  enchiladas.steps = [
    "Poach boneless, skinless chicken thighs in gently simmering water 18–22 minutes to 165°F; shred. Heat oven to 400°F.",
    "Mix chicken, wilted spinach, drained green chiles and half the Monterey Jack. Whisk salsa verde with sour cream.",
    "Warm gluten-free corn tortillas until pliable, fill and roll. Arrange seam-side down, cover with sauce and remaining cheese, and bake about 20 minutes until the center reaches 165°F.",
    "Serve with chopped fresh romaine, thinly sliced red onion and cilantro. Add lime wedges.",
  ];
  enchiladas.notes =
    "Shani uses sour cream or regular cream in the green sauce and serves the enchiladas with romaine, onion and cilantro. Choose the sauce version before planning groceries.";
  enchiladas.variations = [
    variation(enchiladas, "sour-cream", "Sour cream sauce"),
    variation(enchiladas, "regular-cream", "Regular cream sauce", {
      ingredients: enchiladas.ingredients.map((i) =>
        i.id === "sourCream" ? I("cream", i.quantity, i.unit) : i,
      ),
      steps: enchiladas.steps.map((s) =>
        s.replace("with sour cream", "with regular cream"),
      ),
    }),
  ];
  const ribs = get("grilled-ribs");
  const shared = ribs.ingredients.filter(
    (i) => !["bbq", "paprika", "sugar", "salt", "pepper"].includes(i.id),
  );
  const plainIngredients = [
    ...shared,
    I("garlic", 6, "each"),
    I("salt", 1, "tsp"),
  ];
  const asianIngredients = [
    ...shared,
    I("garlic", 6, "each"),
    I("gochujang", 1, "tbsp"),
    I("fishSauce", 1, "tbsp"),
    I("ginger", 1, "tbsp"),
    I("aminos", 2, "tbsp"),
  ];
  ribs.variations = [
    variation(ribs, "barbecue", "Barbecue glaze"),
    variation(ribs, "garlic-salt", "Plain garlic & salt", {
      ingredients: plainIngredients,
      steps: [
        "Prepare the grill for indirect heat at 300°F. Rub bone-in baby back ribs with finely grated garlic and salt; no barbecue glaze or sugar is used.",
        "Grill covered over indirect heat for about 2½–3 hours until very tender, usually 190–203°F. Pork safety minimum is 145°F with a 3-minute rest; ribs need longer for tenderness.",
        "Grill corn for 12–15 minutes. Toss shredded cabbage and carrot with vinegar and olive oil. Rest ribs 10 minutes before serving with corn and slaw.",
      ],
      description:
        "Bone-in baby back ribs simply seasoned with garlic and salt, grilled slowly until tender, and served with corn and crunchy cabbage-carrot slaw.",
    }),
    variation(ribs, "asian", "Garlic, gochujang, ginger & Bragg’s", {
      ingredients: asianIngredients,
      steps: [
        "Prepare the grill for indirect heat at 300°F. Mix grated garlic and ginger with certified gluten-free gochujang, fish sauce and Bragg Liquid Aminos. Start with less gochujang if sensitive to heat.",
        "Reserve half the clean sauce for finishing. Rub the other half onto ribs. Grill covered over indirect heat about 2½–3 hours until very tender, usually 190–203°F. Brush reserved sauce on during the final 10–15 minutes; never reuse marinade that touched raw pork.",
        "Grill corn and toss cabbage-carrot slaw with vinegar and olive oil. Rest ribs 10 minutes, then serve with the vegetables.",
      ],
      notes:
        "Shani requested garlic, gochujang, fish sauce, ginger and Bragg Liquid Aminos. Use certified gluten-free gochujang and fish sauce. No barbecue sauce is purchased for this version.",
      description:
        "Bone-in baby back ribs glazed with garlic, gochujang, fish sauce, ginger and Bragg Liquid Aminos, with grilled corn and crunchy slaw.",
    }),
  ];
  const mushroomChicken = get("mushroom-chicken");
  mushroomChicken.variations = [
    variation(mushroomChicken, "coconut-cream", "Coconut cream"),
    variation(mushroomChicken, "regular-cream", "Regular cream", {
      ingredients: mushroomChicken.ingredients.map((i) =>
        i.id === "coconutCream" ? I("cream", i.quantity, i.unit) : i,
      ),
      steps: mushroomChicken.steps.map((s) =>
        s.replace("coconut cream", "regular cream"),
      ),
    }),
  ];
  update("shepherds-pie", {
    title: "Beef Shepherd’s Pie",
    protein: "Beef",
    cut: "Ground beef, 85% lean",
    ingredients: get("shepherds-pie").ingredients.map((i) =>
      i.id === "lambGround" ? I("groundBeef", i.quantity, i.unit) : i,
    ),
    steps: get("shepherds-pie").steps.map((s) =>
      s
        .replaceAll("ground lamb", "ground beef")
        .replaceAll("Lamb must", "Ground beef must"),
    ),
    notes:
      "Shani requested the ground-beef version, also called cottage pie. Use ground beef as the default; this recipe no longer buys ground lamb.",
  });
  const mushrooms = get("mushroom-pasta");
  update("mushroom-pasta", {
    title: "Mixed Mushroom & Rosemary Pasta",
    vegetables: "Cremini, shiitake & oyster mushrooms with spinach",
    ingredients: [
      ...mushrooms.ingredients.filter((i) => i.id !== "mushroom"),
      I("mushroom", 0.5, "lb"),
      I("shiitake", 0.5, "lb"),
      I("oysterMushroom", 0.5, "lb"),
    ],
    steps: [
      "Cook gluten-free pasta in salted water and reserve 1 cup pasta water. Trim tough shiitake stems, slice cremini and shiitake caps, and tear oyster mushrooms into strips.",
      "Brown the three mushroom varieties in olive oil in uncrowded batches, 6–8 minutes per batch. Add minced garlic and chopped rosemary for the final minute.",
      "Wilt spinach into the mushrooms. Toss with pasta, lemon juice and enough reserved pasta water to coat. Season to taste.",
    ],
    notes:
      "Use a mixture of cremini, shiitake and oyster mushrooms for different textures. An available mixed-mushroom pack is an alternative, but keep the total mushroom amount at 1½ lb for 3 generous portions.",
  });

  for (const r of recipes) {
    r.description = descriptions[r.id] || r.description;
    r.catalogRevision = 2;
    r.image = `/images/recipes/${r.id}.webp`;
    r.imageAlt = `Illustration of ${r.title}`;
    r.dairy = r.ingredients.some((i) => dairyIds.has(i.id));
    if (r.variations)
      for (const v of r.variations) {
        v.description =
          v.description === get(r.id).description
            ? r.description
            : v.description || r.description;
        v.dairy = v.ingredients.some((i) => dairyIds.has(i.id));
        v.image =
          r.id === "grilled-ribs" && v.id !== "barbecue"
            ? `/images/recipes/grilled-ribs-${v.id}.webp`
            : r.image;
        if (r.id === "thai-beef" && v.id === "shaved-beef")
          v.image = "/images/recipes/thai-beef-shaved-beef.webp";
        if (r.id === "schnitzel" && v.id === "slaw")
          v.image = "/images/recipes/schnitzel-slaw.webp";
        if (r.id !== "grilled-ribs") v.description = r.description;
      }
    if (
      [
        "thai-beef",
        "poke",
        "vodka-rigatoni",
        "schnitzel",
        "lamb-burgers",
        "harissa-lamb",
        "harissa-chicken",
        "enchiladas",
        "grilled-ribs",
        "mushroom-chicken",
        "shepherds-pie",
        "mushroom-pasta",
      ].includes(r.id)
    ) {
      r.sourceNote +=
        " Household ingredients or sides were clarified by Shani during recipe review. Quantities remain proposed for kitchen review.";
    }
  }
  // The primary BBQ option uses the new overview copy as well.
  ribs.variations[0].description = ribs.description;
}
